THINQ_SERVICE_LOAD_DIAGNOSTICS: List[Dict[str, Any]] = []


class _UnavailableThinqService:
    """Non-crashing service placeholder used only when all imports fail.

    This keeps the daily web build alive while making the failure explicit in
    outputs/latest_*.json and in the run manifest. Returning a structured
    payload is safer than silently producing 0%/N/A values without an import
    reason.
    """

    def __init__(self, diagnostics: List[Dict[str, Any]]) -> None:
        self._corq_import_module = None
        self._corq_import_file = None
        self._corq_import_diagnostics = diagnostics

    def build_match_features(self, *args: Any, **kwargs: Any) -> Dict[str, Any]:
        return {
            "available": False,
            "thinq_available": False,
            "error": "THINQ_SERVICE_IMPORT_FAILED",
            "flags": ["THINQ_SERVICE_IMPORT_FAILED"],
            "thinq_flags": ["THINQ_SERVICE_IMPORT_FAILED"],
            "thinq_service_import_diagnostics": self._corq_import_diagnostics,
        }


def _load_thinq_service():
    """Load exactly one ThinQ service implementation, with diagnostics.

    The canonical implementation is `thinq.service`. `corq.service` must be a
    compatibility wrapper only. This loader records the module path so future
    path mix-ups are visible in the manifest and in enriched rows.
    """
    global THINQ_SERVICE_LOAD_DIAGNOSTICS
    THINQ_SERVICE_LOAD_DIAGNOSTICS = []
    candidates = (
        "thinq.service",
        "corq.service",
        "thinq.thinq_service",
    )
    for module_name in candidates:
        try:
            module = importlib.import_module(module_name)
            service_cls = getattr(module, "ThinqService")
            service = service_cls()
            setattr(service, "_corq_import_module", module_name)
            setattr(service, "_corq_import_file", getattr(module, "__file__", None))
            setattr(service, "_corq_import_diagnostics", list(THINQ_SERVICE_LOAD_DIAGNOSTICS))
            return service
        except Exception as exc:
            THINQ_SERVICE_LOAD_DIAGNOSTICS.append({
                "module": module_name,
                "ok": False,
                "error": f"{type(exc).__name__}: {exc}",
                "traceback_tail": traceback.format_exc(limit=4).splitlines()[-8:],
            })
    return _UnavailableThinqService(list(THINQ_SERVICE_LOAD_DIAGNOSTICS))


def _ranking_norm_name(value: Any) -> str:
    """Normalize player names for info-only ranking lookup.

    Ranking is intentionally NOT used in model probability or TOP7 ranking score.
    This lookup only replaces the old TA ranking display/cache dependency.
    """
    text = str(value or "").strip().lower()
    text = unicodedata.normalize("NFKD", text)
    text = "".join(ch for ch in text if not unicodedata.combining(ch))
    text = re.sub(r"[^a-z0-9]+", " ", text)
    return " ".join(text.split())


def _ranking_compact_name(value: Any) -> str:
    return _ranking_norm_name(value).replace(" ", "")


def _to_int_or_none(value: Any) -> Optional[int]:
    try:
        if value in (None, "", "—", "-", "N/A"):
            return None
        return int(float(str(value).replace(",", "")))
    except Exception:
        return None


def _extract_tennisapi_ranking_rows(payload: Any) -> List[Dict[str, Any]]:
    """Extract ranking rows from several known/probable TennisApi shapes.

    Supported shapes include:
    - {"players_by_name": {...}} cache generated by update-ta-rankings.yml replacement
    - {"rankings": [...]}
    - {"data": [...]}
    - nested lists/dicts containing ranking/team/player fields
    """
    rows: List[Dict[str, Any]] = []
    if isinstance(payload, dict):
        players_by_name = payload.get("players_by_name")
        if isinstance(players_by_name, dict):
            for item in players_by_name.values():
                if isinstance(item, dict):
                    rows.append(item)
            return rows
        for key in ("rankings", "data", "result", "results", "items"):
            value = payload.get(key)
            if isinstance(value, list):
                for item in value:
                    rows.extend(_extract_tennisapi_ranking_rows(item))
            elif isinstance(value, dict):
                rows.extend(_extract_tennisapi_ranking_rows(value))
        if any(k in payload for k in ("ranking", "rank", "position", "rankingPoints", "points", "team", "player")):
            rows.append(payload)
    elif isinstance(payload, list):
        for item in payload:
            rows.extend(_extract_tennisapi_ranking_rows(item))
    return rows


def _ranking_row_to_player(row: Dict[str, Any], tour_hint: Optional[str] = None) -> Optional[Dict[str, Any]]:
    team = row.get("team") if isinstance(row.get("team"), dict) else {}
    player = row.get("player") if isinstance(row.get("player"), dict) else {}
    entity = team or player
    name = (
        row.get("name")
        or row.get("playerName")
        or row.get("teamName")
        or entity.get("name")
        or entity.get("shortName")
    )
    if not name:
        return None
    rank = _to_int_or_none(row.get("ranking") or row.get("rank") or row.get("position"))
    points = _to_int_or_none(row.get("points") or row.get("rankingPoints") or row.get("ranking_points"))
    if rank is None and points is None:
        return None
    category = row.get("category") if isinstance(row.get("category"), dict) else {}
    tour = (
        tour_hint
        or row.get("tour")
        or row.get("ranking_category")
        or category.get("name")
        or category.get("slug")
        or row.get("categoryName")
    )
    player_id = row.get("id") or row.get("player_id") or entity.get("id")
    out = {
        "name": str(name),
        "norm_name": _ranking_norm_name(name),
        "compact_name": _ranking_compact_name(name),
        "rank": rank,
        "points": points,
        "tour": str(tour).upper() if tour else None,
        "player_id": player_id,
        "country": (entity.get("country") or {}).get("name") if isinstance(entity.get("country"), dict) else entity.get("country"),
        "source": row.get("source") or "TENNISAPI_RANKINGS",
    }
    return out


def _load_tennisapi_rankings_info(output_root: str = "outputs") -> Dict[str, Any]:
    """Load info-only rankings generated from TennisApi.

    This intentionally replaces only the old TA ranking cache/update workflow.
    It does not affect CorQ/ThinQ/MMx probabilities or ranking score.
    """
    candidate_paths = [
        Path(output_root) / "rankings" / "tennisapi_rankings.json",
        Path("data/api_pro/rankings/tennisapi_rankings.json"),
        Path("data/rankings/tennisapi_rankings.json"),
        Path("outputs/tennisapi_rankings.json"),
    ]
    source_path = None
    payload: Any = None
    for path in candidate_paths:
        try:
            if path.exists():
                payload = json.loads(path.read_text(encoding="utf-8"))
                source_path = path
                break
        except Exception:
            continue
    players_by_name: Dict[str, Dict[str, Any]] = {}
    players_by_compact: Dict[str, Dict[str, Any]] = {}
    if payload is not None:
        raw_rows = _extract_tennisapi_ranking_rows(payload)
        for row in raw_rows:
            if isinstance(row, dict):
                player = _ranking_row_to_player(row)
                if not player:
                    continue
                if player["norm_name"]:
                    players_by_name[player["norm_name"]] = player
                if player["compact_name"]:
                    players_by_compact[player["compact_name"]] = player
    return {
        "status": "OK" if players_by_name else "NO_RANKING_CACHE",
        "source": "TENNISAPI_RANKINGS",
        "source_path": str(source_path) if source_path else None,
        "players_by_name": players_by_name,
        "players_by_compact": players_by_compact,
        "player_count": len(players_by_name),
    }


def _lookup_ranking_player(rankings: Dict[str, Any], name: Any) -> Optional[Dict[str, Any]]:
    if not isinstance(rankings, dict):
        return None
    norm = _ranking_norm_name(name)
    compact = _ranking_compact_name(name)
    by_name = rankings.get("players_by_name") if isinstance(rankings.get("players_by_name"), dict) else {}
    by_compact = rankings.get("players_by_compact") if isinstance(rankings.get("players_by_compact"), dict) else {}
    return by_name.get(norm) or by_compact.get(compact)


def _enrich_with_tennisapi_ranking_info(record: Dict[str, Any], rankings: Dict[str, Any]) -> Dict[str, Any]:
    """Attach current rank/points info only.

    No probability, confidence or TOP7 ranking logic is changed here.
    Compatibility TA display aliases are kept so existing UI does not break.
    """
    pick_name = record.get("pick") or record.get("player") or record.get("player1")
    opponent_name = record.get("opponent") or record.get("opp") or record.get("player2")
    pick_row = _lookup_ranking_player(rankings, pick_name)
    opp_row = _lookup_ranking_player(rankings, opponent_name)
    pick_rank = _to_int_or_none((pick_row or {}).get("rank"))
    opp_rank = _to_int_or_none((opp_row or {}).get("rank"))
    pick_points = _to_int_or_none((pick_row or {}).get("points"))
    opp_points = _to_int_or_none((opp_row or {}).get("points"))
    record["ranking_source"] = "TENNISAPI_RANKINGS"
    record["ranking_status"] = "OK" if pick_rank is not None or opp_rank is not None else rankings.get("status", "NO_RANKING_CACHE")
    record["ranking_cache_path"] = rankings.get("source_path")
    record["pick_rank"] = pick_rank
    record["opponent_rank"] = opp_rank
    record["pick_rank_points"] = pick_points
    record["opponent_rank_points"] = opp_points
    record["rank_gap"] = (opp_rank - pick_rank) if pick_rank is not None and opp_rank is not None else None
    record["rank_points_gap"] = (pick_points - opp_points) if pick_points is not None and opp_points is not None else None
    record["pick_rank_display"] = f"#{pick_rank}" if pick_rank is not None else "(X)"
    record["opponent_rank_display"] = f"#{opp_rank}" if opp_rank is not None else "(X)"
    record["pick_rank_points_display"] = str(pick_points) if pick_points is not None else "N/A"
    record["opponent_rank_points_display"] = str(opp_points) if opp_points is not None else "N/A"
    # Backward-compatible aliases for render code that still expects TA rank display keys.
    record["pick_ta_rank_display"] = record["pick_rank_display"]
    record["opponent_ta_rank_display"] = record["opponent_rank_display"]
    record["ta_ranking_replaced_by"] = "TENNISAPI_RANKINGS_INFO_ONLY"
    return record



