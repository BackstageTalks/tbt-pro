def _enrich_with_marq(record: Dict[str, Any]) -> Dict[str, Any]:
    """Attach TennisApi-only MarQ V2 fields to a scored match row.

    The previous flow called marq.pipeline without passing exact event context,
    so rows frequently degraded to RuntimeOddsFallback even though event ids and
    odds endpoint attempts existed. This implementation calls marq.provider
    directly with the full row context, preserving exact-event MarQ audit fields.
    """
    output = dict(record)
    event_id = _first_present(output.get("event_id"), output.get("match_id"), output.get("id"))
    home_odds, away_odds = _home_away_odds_pair(output)

    market: Optional[Dict[str, Any]] = None
    try:
        from marq.provider import fetch_marq_market_data  # type: ignore
        market = fetch_marq_market_data(
            player1=str(output.get("player1") or ""),
            player2=str(output.get("player2") or ""),
            date_only=_date_only_for_marq(output),
            pick=str(output.get("pick") or output.get("player") or "") or None,
            odds_player1=home_odds,
            odds_player2=away_odds,
            event_id=event_id,
            match_id=output.get("match_id"),
            tennisapi_event_id=output.get("tennisapi_event_id"),
            id=output.get("id"),
            raw=output.get("raw") if isinstance(output.get("raw"), dict) else None,
            row=output,
        )
    except Exception as exc:
        output.setdefault("marq_error", str(exc))

    if isinstance(market, dict) and market:
        output = _merge_marq_v2_market(output, market)
    else:
        fallback = _fallback_marq_from_row(output)
        if fallback:
            for key, value in fallback.items():
                output.setdefault(key, value)
            _tag_thin_fallback(output)

    if output.get("marq_edge_pct") in (None, ""):
        try:
            pick_pct = float(output.get("marq_crowd_pick_pct"))
            output["marq_edge_pct"] = round(pick_pct - 50.0, 1)
        except Exception:
            pass
    if output.get("marq_final") in (None, ""):
        try:
            edge = float(output.get("marq_edge_pct"))
            output["marq_final"] = "Market With Pick" if edge >= 2.0 else "Market Against Pick" if edge <= -2.0 else "Neutral"
            output["marq_final_display"] = output["marq_final"]
        except Exception:
            output.setdefault("marq_final", "Pending")

    # CLV snapshot enrichment is optional and must not overwrite MarQ V2 data.
    try:
        from marq.odds_snapshots import enrich_row_with_internal_marq  # type: ignore
        output = enrich_row_with_internal_marq(output)
    except Exception as exc:
        output.setdefault("marq_internal_error", str(exc))
    return output

def _enrich_with_sets_games(record: Dict[str, Any]) -> Dict[str, Any]:
    """Attach Sets/Games market-aware fields from marq.market_lines.

    This is intentionally soft-fail: if market helpers or upstream APIs are not
    available, the CORQ runtime continues and the renderer shows N/A/Pending.
    """
    try:
        from marq.market_lines import build_sets_games_from_match, build_sets_games_value_candidates  # type: ignore
    except Exception as exc:
        record.setdefault("sets_games_status", "UNAVAILABLE")
        record.setdefault("sets_games_error", str(exc))
        record.setdefault("sets_games_best_value", "Pending lines")
        return record

    try:
        model_prediction = {
            "probability_player1": record.get("probability_player1") or record.get("p1_probability") or record.get("player1_probability"),
            "probability_player2": record.get("probability_player2") or record.get("p2_probability") or record.get("player2_probability"),
        }
        enriched = build_sets_games_from_match(record, model_prediction=model_prediction)
        if isinstance(enriched, dict):
            record.update(enriched)
        value_candidates = build_sets_games_value_candidates(record)
        record["sets_games_value_candidates"] = value_candidates
        if value_candidates and value_candidates[0].get("selection"):
            record["sets_games_best_value"] = value_candidates[0].get("selection")
            record["sets_games_best_value_edge"] = value_candidates[0].get("edge")
        else:
            record.setdefault("sets_games_best_value", "Pending lines")
        record.setdefault("sets_games_status", "OK")
    except Exception as exc:
        record.setdefault("sets_games_status", "ERROR")
        record.setdefault("sets_games_error", str(exc))
        record.setdefault("sets_games_best_value", "Pending lines")
    return record


def _probability_ratio(value: Any) -> Optional[float]:
    num = _num(value)
    if num is None:
        return None
    if num > 1.0:
        num /= 100.0
    if 0.0 <= num <= 1.0:
        return num
    return None


def _first_probability_ratio(record: Dict[str, Any], *keys: str) -> Optional[float]:
    for key in keys:
        value = record.get(key)
        ratio = _probability_ratio(value)
        if ratio is not None:
            return ratio
    return None


def _price_bucket_label(odds: Optional[float]) -> str:
    if odds is None:
        return "Unknown"
    if odds < 1.50:
        return "Short"
    if odds <= 2.20:
        return "Fair"
    return "Long Risk"


def _value_bucket_label(delta_pp: Optional[float]) -> str:
    if delta_pp is None:
        return "Unknown"
    if delta_pp >= 3.0:
        return "Value+"
    if delta_pp >= -2.0:
        return "Neutral"
    return "No Value"


def _enrich_with_price_value(record: Dict[str, Any]) -> Dict[str, Any]:
    """Attach non-filtering betting-value audit fields.

    These fields do NOT select or reject picks. They only make price/value
    visible in CorQ, Audit and Results snapshots:
    - raw implied probability = 1 / pick odds
    - Value Delta = CorQ probability - raw implied probability
    - EV = CorQ probability * decimal odds - 1
    """
    odds = _decimal_odds(
        _first_present(
            record.get("pick_odds"),
            record.get("odds"),
            record.get("selected_odds"),
            record.get("odds_decimal"),
            record.get("decimal_odds"),
        )
    )
    corq_prob = _first_probability_ratio(
        record,
        "corq_calibrated_probability",
        "corq_probability",
        "corq_estimated_win_probability",
        "win_probability",
        "estimated_win_probability",
        "probability",
    )
    if odds is None or corq_prob is None or odds <= 0:
        record.setdefault("price_value_status", "MISSING_VALUE_INPUT")
        return record

    raw_implied = 1.0 / odds
    delta_pp = (corq_prob - raw_implied) * 100.0
    ev_ratio = (corq_prob * odds) - 1.0
    ev_pct = ev_ratio * 100.0

    price_bucket = _price_bucket_label(odds)
    value_bucket = _value_bucket_label(delta_pp)
    price_slug = price_bucket.upper().replace(" ", "_")
    value_slug = (
        "VALUE_POSITIVE" if value_bucket == "Value+" else
        "VALUE_NEUTRAL" if value_bucket == "Neutral" else
        "VALUE_NEGATIVE" if value_bucket == "No Value" else
        "VALUE_UNKNOWN"
    )

    record["raw_implied_probability"] = round(raw_implied, 6)
    record["raw_implied_probability_pct"] = round(raw_implied * 100.0, 2)
    record["break_even_probability"] = round(raw_implied, 6)
    record["break_even_probability_pct"] = round(raw_implied * 100.0, 2)
    record["corq_value_delta_pp"] = round(delta_pp, 2)
    record["expected_value"] = round(ev_ratio, 6)
    record["expected_value_pct"] = round(ev_pct, 2)
    record["price_value_grade"] = price_slug
    record["price_value_tag"] = value_slug
    record["price_value_display"] = f"{price_bucket} | {value_bucket}"
    record["price_value_status"] = "OK"
    tags = [price_slug, value_slug]
    existing = record.get("price_value_tags")
    if isinstance(existing, list):
        tags = list(dict.fromkeys([str(x) for x in existing if x] + tags))
    record["price_value_tags"] = tags
    return record

def _betting_day_context(run_date: Optional[str] = None) -> Dict[str, str]:
    """Return the Europe/Bratislava betting day window: 06:00 to 06:00.

    Matches after midnight but before 06:00 local time belong to the previous
    betting day. This is used for immutable morning snapshots and Results.
    """
    tz = ZoneInfo("Europe/Bratislava")
    if run_date:
        base_day = datetime.fromisoformat(str(run_date)[:10]).date()
    else:
        now = datetime.now(tz)
        base_day = now.date() - timedelta(days=1) if now.hour < 6 else now.date()
    start_local = datetime.combine(base_day, time(hour=6), tzinfo=tz)
    end_local = start_local + timedelta(days=1)
    return {
        "betting_day": base_day.isoformat(),
        "snapshot_date": base_day.isoformat(),
        "betting_day_start_local": start_local.isoformat(),
        "betting_day_end_local": end_local.isoformat(),
        "timezone": "Europe/Bratislava",
    }


def _snapshot_rows(rows: List[Dict[str, Any]], *, snapshot_type: str, context: Dict[str, str]) -> List[Dict[str, Any]]:
    out: List[Dict[str, Any]] = []
    snapshot_id = f"{snapshot_type}_{context['betting_day']}"
    created_at = datetime.now(timezone.utc).isoformat()
    for idx, row in enumerate(rows or [], start=1):
        if not isinstance(row, dict):
            continue
        item = dict(row)
        item.setdefault("snapshot_id", snapshot_id)
        item.setdefault("snapshot_type", snapshot_type)
        item.setdefault("snapshot_source", "CORQ_DAILY")
        item.setdefault("snapshot_rank", idx)
        item.setdefault("snapshot_date", context["snapshot_date"])
        item.setdefault("betting_day", context["betting_day"])
        item.setdefault("betting_day_start_local", context["betting_day_start_local"])
        item.setdefault("betting_day_end_local", context["betting_day_end_local"])
        item.setdefault("snapshot_timezone", context["timezone"])
        item.setdefault("snapshot_created_at_utc", created_at)
        item.setdefault("results_status", "PENDING")
        out.append(item)
    return out


